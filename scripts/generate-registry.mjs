#!/usr/bin/env node
/**
 * Generates apps/api/src/plugins/registry.ts by scanning plugin directories
 * under plugins/<dir>/.
 *
 * Each plugin is a workspace package containing:
 *   - manifest.json  (PluginManifest)
 *   - package.json   (name like "@pressforge-plugins/hello-world")
 *
 * Output supplies the build-time plugin registry used by the Worker:
 *   pluginManifests — metadata (name, version, requires, description)
 *   pluginEntries   — lazy () => import(pkg) resolvers
 */
import { readdirSync, readFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pluginsDir = join(root, 'plugins');
const outDir = join(root, 'apps', 'api', 'src', 'plugins');
const outFile = join(outDir, 'registry.ts');

const entries = [];
const manifests = {};

if (existsSync(pluginsDir)) {
  for (const dir of readdirSync(pluginsDir, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue;
    const manifestPath = join(pluginsDir, dir.name, 'manifest.json');
    const pkgPath = join(pluginsDir, dir.name, 'package.json');
    if (!existsSync(manifestPath)) continue;

    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
    const id = manifest.id;
    if (!id) {
      console.error(`[registry] plugins/${dir.name}/manifest.json missing "id"`);
      process.exit(1);
    }
    const pkgName = existsSync(pkgPath) ? JSON.parse(readFileSync(pkgPath, 'utf8')).name : `@pressforge-plugins/${id}`;

    manifests[id] = { ...manifest, entry: pkgName };
    entries.push({ id, pkgName, manifest });
  }
}

const manifestBlock = entries
  .map(({ id, manifest }) => `  ${JSON.stringify(id)}: ${JSON.stringify(manifest, null, 2).replace(/\n/g, '\n  ')},`)
  .join('\n');
const entryBlock = entries
  .map(({ id, pkgName }) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify(pkgName)}),`)
  .join('\n');

const content = `// AUTO-GENERATED by scripts/generate-registry.mjs — do not edit manually.
import type { PluginManifest } from '@pressforge/core';

export const pluginManifests: Record<string, PluginManifest> = {
${manifestBlock}
};

export const pluginEntries: Record<string, () => Promise<{ default: import('@pressforge/core').PluginRegistration }>> = {
${entryBlock}
};
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, content, 'utf8');
console.log(`[registry] scanned ${entries.length} plugin(s) -> ${outFile}`);